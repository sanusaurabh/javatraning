package arrayPracticeQuestions;

public class Task4 {

    /* Create an array of 4 integers, assign values 5, 10, 15 and 20 individually , tjen print all four elements. */
    public static void main(String[] args) {
        int[] i = new int[4];
        i[0] = 5;
        i[1] = 10;
        i[2] = 15;
        i[3] = 20;

        System.out.println(i[0]);
        System.out.println(i[1]);
        System.out.println(i[2]);
        System.out.println(i[3]);
    }
}
