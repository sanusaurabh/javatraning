package moduluswithhardcodedvalues;

public class ModuloFloatNumbers {
    public static void main(String[] args) {

        float num1 = 565.43f;
        float num2 = 43.5f;

        float modulus = num1 % num2;

        System.out.println("The modulus of two float numbers is - " + modulus);

    }
}
